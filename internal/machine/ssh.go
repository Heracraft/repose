package machine

import (
	"fmt"
	"os"
	"path/filepath"
	"runtime"
	"sort"
	"strings"
)

// SSHName is the file in ~/.ssh/repose with one Host block per machine.
// It is its own file and not the gateway's `hosts`
// (internal/cli/cert.go), so a laptop holds hosted projects and owned
// machines at once.
const SSHName = "machines"

// KnownHostsName is where the machines' host keys are remembered. The
// hosted path pins a CA (internal/cli/cert.go writes an
// @cert-authority line); a machine the user owns has no CA and no
// gateway, so its key is learned on the first connection and refused if
// it ever changes — `accept-new`, not `no` (DECISIONS I-812). It is
// repose's own file so that trusting a box for repose does not add a key
// to the user's ~/.ssh/known_hosts.
const KnownHostsName = "machine_known_hosts"

// SSHConfig renders ~/.ssh/repose/machines. A registry it cannot read
// renders no blocks: the interface has no error to return, and WriteSSH,
// which is what puts the file on disk, reports the error itself.
func (r *FileRegistry) SSHConfig(prefix string) string {
	ms, _ := r.load()
	return RenderSSHConfig(ms, prefix, runtime.GOOS != "windows")
}

// WriteSSH writes dir/machines when it differs from what this binary
// would write, where dir is ~/.ssh/repose (internal/cli sshDir). A
// registry it cannot read is an error and leaves the file alone: the
// blocks already on disk reach more than an empty file does.
func (r *FileRegistry) WriteSSH(dir, prefix string) error {
	ms, err := r.load()
	if err != nil {
		return err
	}
	want := RenderSSHConfig(ms, prefix, runtime.GOOS != "windows")
	path := filepath.Join(dir, SSHName)
	if have, err := os.ReadFile(path); err == nil && string(have) == want {
		return nil
	}
	return writeFileAtomic(path, []byte(want), 0o600)
}

// RenderSSHConfig builds ~/.ssh/repose/machines: one Host block per
// machine, in name order for a stable diff. prefix spells the home
// directory (internal/cli sshPathPrefix). multiplex adds the ControlMaster
// lines, which OpenSSH on Windows has not got.
//
// The blocks carry no certificate and no gateway. A machine the user owns
// answers on its own address, with the key `repose machine add --key`
// named.
func RenderSSHConfig(ms []Machine, prefix string, multiplex bool) string {
	sorted := append([]Machine(nil), ms...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	var b strings.Builder
	b.WriteString("# Generated by repose; edits here are overwritten. ~/.ssh/repose/config includes this file.\n")
	for _, m := range sorted {
		_, _ = fmt.Fprintf(&b, "Host %s\n", Alias(m.Name))
		_, _ = fmt.Fprintf(&b, "  HostName %s\n", m.Address)
		if m.Port != 0 && m.Port != DefaultPort {
			_, _ = fmt.Fprintf(&b, "  Port %d\n", m.Port)
		}
		_, _ = fmt.Fprintf(&b, "  User %s\n", m.Login)
		// The named key and only it: with an agent loaded ssh otherwise
		// offers the agent's keys first (I-108). A machine added without
		// one gets neither line, so ssh goes on using the agent.
		if m.KeyPath != "" {
			_, _ = fmt.Fprintf(&b, "  IdentityFile %s\n", sshQuote(m.KeyPath))
			b.WriteString("  IdentitiesOnly yes\n")
		}
		_, _ = fmt.Fprintf(&b, "  UserKnownHostsFile %s\n", homePath(prefix, ".ssh/repose/"+KnownHostsName))
		// The box's key is learned once and pinned after that: a changed
		// key is refused, which is the half of strict checking that
		// matters when there is no CA to pin instead.
		b.WriteString("  StrictHostKeyChecking accept-new\n")
		// No agent forwarding (I-247): anything running on the box could
		// sign with the laptop's keys while it is attached.
		b.WriteString("  ForwardAgent no\n")
		b.WriteString("  ServerAliveInterval 30\n")
		if multiplex {
			// One handshake per `repose run`: every later ssh rides this
			// connection (I-149).
			b.WriteString("  ControlMaster auto\n")
			_, _ = fmt.Fprintf(&b, "  ControlPath %s\n", homePath(prefix, ".ssh/repose/cm-%C"))
			b.WriteString("  ControlPersist 10m\n")
		}
	}
	return b.String()
}

// IncludeLine is the line ~/.ssh/repose/config needs for the machine
// blocks to be read, beside the Include that file already has for the
// gateway's hosts (internal/cli/sshprepare.go renderSSHEntry).
func IncludeLine(prefix string) string {
	return fmt.Sprintf("Include %s\n", homePath(prefix, ".ssh/repose/"+SSHName))
}

// sshQuote quotes a path for a config line when it has a space, as
// internal/cli's sshPath does.
func sshQuote(p string) string {
	if strings.ContainsAny(p, " \t") {
		return `"` + p + `"`
	}
	return p
}

// homePath is a path under the home directory as the generated files
// spell it: prefix is "~" or the home directory written out.
func homePath(prefix, rel string) string { return sshQuote(prefix + "/" + rel) }
